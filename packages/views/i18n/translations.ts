export function interpolate(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    params[key] == null ? match : String(params[key]),
  );
}

function withOriginalWhitespace(
  source: string,
  translated: string | undefined,
): string {
  if (!translated || translated === source) return source;
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

function translateTrimmedPhrase(trimmed: string): string | undefined {
  const exact = EXACT_ZH[trimmed];
  if (exact) return exact;

  for (const entry of DYNAMIC_ZH) {
    const match = trimmed.match(entry.pattern);
    if (match) return entry.replace(...match);
  }

  return undefined;
}

export function translatePhrase(value: string, locale: AppLocale): string {
  if (locale !== "zh") return value;
  const trimmed = value.trim();
  if (!trimmed) return value;
  return withOriginalWhitespace(value, translateTrimmedPhrase(trimmed));
}

